/// Provides JavaFX skins used by M3FX controls.
///
/// Applications normally do not instantiate these classes directly. They are public so advanced users can
/// subclass, inspect, or replace skins through the standard JavaFX `Skin` API, but the supported component
/// surface is defined by the controls in [org.glavo.m3fx.controls]. The skins implement Material Design 3
/// layout, state layers, ripple feedback, focus indication, elevation, and motion using the active M3FX
/// token set.
///
/// See [Material Design](https://m3.material.io/) and the
/// [Material Design component catalog](https://m3.material.io/components) for the component behavior mirrored
/// by these skins.
